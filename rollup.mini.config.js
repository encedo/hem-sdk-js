// rollup.mini.config.js — a build of the SDK with only the HEM methods a
// project calls: the linker's dead-code stripping, for a class.
//
//   KEEP=path/to/keep.json OUT=path/to/hem-sdk.mini.js \
//     npx --yes rollup@4.63.2 -c rollup.mini.config.js
//
// keep.json is a JSON array of HEM method names (public ones), or an object
// { "methods": [...], "exports": [...] } - the module's exports, HEM and
// HemError when not given. The plugin
// parses hem-sdk.js, adds every method a kept one calls through `this.<name>`
// or `this.#<name>` (to a fixed point), removes every other method of class
// HEM, and leaves the rest to rollup's tree-shaking: a helper, a constant or a
// class (Attest, Broker) that no kept method reaches is dropped with it.
//
// The output is an ES module with the same exports as hem-sdk.js; a method
// that was not kept does not exist (`hem.uploadFirmware` is undefined), so a
// project that starts calling one fails at once and adds it to its list. The
// same input gives the same bytes: what an auditor reads is exactly what ships.

import { readFileSync } from 'node:fs';

const keepFile = process.env.KEEP;
const out = process.env.OUT;
if (!keepFile || !out) throw new Error('KEEP=<keep.json> and OUT=<file> are required');
const spec = JSON.parse(readFileSync(keepFile, 'utf8'));
const keep = Array.isArray(spec) ? spec : spec.methods;
const exportsWanted = (!Array.isArray(spec) && spec.exports) || ['HEM', 'HemError'];
const names = (a) => Array.isArray(a) && a.every((m) => typeof m === 'string' && /^[A-Za-z_$][\w$]*$/.test(m));
if (!names(keep) || !names(exportsWanted)) throw new Error('keep.json: method and export names');
const ENTRY = '\0hem-sdk-mini-entry';

/** Method name of a class element, `#x` for a private one; null for anything computed. */
function nameOf(el) {
  if (el.key?.type === 'Identifier') return el.key.name;
  if (el.key?.type === 'PrivateIdentifier') return '#' + el.key.name;
  return null;
}

let kept = '';

function stripHem() {
  return {
    name: 'strip-hem-methods',
    resolveId(id) { return id === ENTRY ? ENTRY : null; },
    load(id) { return id === ENTRY ? `export { ${exportsWanted.join(', ')} } from ${JSON.stringify(new URL('./hem-sdk.js', import.meta.url).pathname)};` : null; },
    transform(code, id) {
      if (!id.endsWith('/hem-sdk.js')) return null;
      const ast = this.parse(code);
      const cls = ast.body.find((n) => n.type === 'ExportNamedDeclaration' && n.declaration?.type === 'ClassDeclaration' && n.declaration.id.name === 'HEM')?.declaration;
      if (!cls) this.error('class HEM not found in hem-sdk.js');
      const methods = new Map();
      for (const el of cls.body.body) {
        const name = nameOf(el);
        if (el.type === 'MethodDefinition' && name && el.kind === 'method' && !el.static) methods.set(name, el);
      }
      for (const m of keep) if (!methods.has(m)) this.error(`keep.json names "${m}", which is not a method of HEM`);
      // Fixed point over `this.name(` / `this.#name(` / `this.name.bind` - what one method needs of another.
      const need = new Set(keep);
      const queue = [...keep];
      while (queue.length) {
        const el = methods.get(queue.pop());
        const body = code.slice(el.start, el.end);
        for (const [, priv, name] of body.matchAll(/this\.(#?)([A-Za-z_$][\w$]*)/g)) {
          const k = priv + name;
          if (methods.has(k) && !need.has(k)) { need.add(k); queue.push(k); }
        }
      }
      const cut = [...methods].filter(([n]) => !need.has(n)).map(([, el]) => el).sort((a, b) => b.start - a.start);
      let s = code;
      for (const el of cut) {
        // Take the JSDoc above the method with it, so the output reads as the source does.
        const before = s.slice(0, el.start);
        // One comment, the one right above it: no "*/" inside, only blanks after.
        const doc = before.match(/\n([ \t]*\/\*\*(?:(?!\*\/)[\s\S])*\*\/[ \t]*\n[ \t]*)$/);
        const from = doc ? el.start - doc[1].length : el.start;
        s = s.slice(0, from) + s.slice(el.end);
      }
      kept = `// HEM methods kept (${[...need].filter((n) => !n.startsWith('#')).length} public, with what they call): ` +
        [...need].sort().join(', ');
      return { code: s, map: null };
    },
  };
}

export default {
  input: ENTRY,
  output: {
    file: out, format: 'es', sourcemap: false,
    banner: () => `// hem-sdk.mini.js - generated by rollup.mini.config.js from hem-sdk.js; do not edit.\n${kept}`,
  },
  external: ['node:https', 'node:http', 'node:url'],
  treeshake: { moduleSideEffects: false, propertyReadSideEffects: false },
  plugins: [stripHem()],
};
